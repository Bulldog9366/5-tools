/** Plain-text rate card for the "Estimate with Claude" prompt. */
export function rateCardSummary() {
  const row = (p: Preset) => {
    const labor = p.laborMode === "hourly" ? `${p.laborHours}hr @ $${p.laborRate}/hr` : p.laborFlat > 0 ? `$${p.laborFlat} flat labor` : "no labor charge";
    const materials = p.materials > 0 ? `$${p.materials} materials` : "no material charge";
    return `- ${p.item} (${p.category}): ${labor}, ${materials}`;
  };
  return ["Labor / Services presets:", ...SERVICE_PRESETS.map(row), "", "Materials / Fees presets:", ...MATERIAL_PRESETS.map(row)].join("\n");
}
